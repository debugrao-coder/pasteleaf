#!/usr/bin/env python3
"""The JSON tokens are canonical; check generated native adapters in CI."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def camel(name):
    head, *tail = name.split('_')
    return head + ''.join(x.title() for x in tail)
def generated():
    t = json.loads((ROOT / 'design/tokens.json').read_text())
    swift = '// Generated by scripts/generate_design_tokens.py; do not edit.\nimport AppKit\nimport CoreGraphics\n\nenum DesignTokens {\n'
    for k, v in t['geometry'].items():
        swift += f'    static let {camel(k)}: {"Double" if k == "motion_seconds" else "CGFloat"} = {v}\n'
    for k, v in t['states'].items():
        swift += f'    static let {camel(k)}: Double = {v}\n'
    swift += '    static let categoryColors: [String] = ' + json.dumps(t['category_colors']) + '\n'
    # Platform-native colors are semantic system roles, not a second hex palette.
    # Keep this mapping here so both design consumers can inspect the adapter contract.
    swift += '    enum MacSystemPalette {\n'
    for role, color in t['platforms']['macos']['colors'].items():
        swift += f'        static var {camel(role)}: NSColor {{ .{color} }}\n'
    swift += '    }\n'
    swift += f'    static let macWindowMaterial: NSVisualEffectView.Material = .{t["platforms"]["macos"]["window_material"]}\n'
    swift += '    struct Palette {\n'
    for k in t['light']:
        swift += f'        let {camel(k)}: String\n'
    swift += '    }\n'
    for theme in ['light', 'dark']:
        swift += f'    static let {theme} = Palette(\n'
        swift += ',\n'.join(f'        {camel(k)}: "{v}"' for k, v in t[theme].items()) + '\n    )\n'
    swift += '}\n'
    rust = '// Generated by scripts/generate_design_tokens.py; do not edit.\n#![allow(dead_code)]\n'
    for k, v in t['geometry'].items():
        rust += f'pub const {k.upper()}: f32 = {float(v)};\n'
    for k, v in t['states'].items():
        rust += f'pub const {k.upper()}: f32 = {float(v)};\n'
    rust += 'pub const CATEGORY_COLORS: &[&str] = &' + json.dumps(t['category_colors']) + ';\n'
    rust += '#[derive(Clone, Copy)]\npub struct Palette {\n'
    for k in t['light']:
        rust += f'    pub {k}: u32,\n'
    rust += '}\n'
    for theme in ['light', 'dark']:
        rust += f'pub const {theme.upper()}: Palette = Palette {{\n'
        rust += ''.join(f'    {k}: 0x{v},\n' for k, v in t[theme].items()) + '};\n'
    return {'clients/macos/Sources/DesignTokens.generated.swift':swift, 'clients/windows/src/design_tokens.rs':rust}
def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a=p.parse_args()
    bad=[]
    for name, content in generated().items():
        path=ROOT/name
        if a.check:
            if not path.exists() or path.read_text()!=content: bad.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    if bad: p.exit(1, 'Token drift: '+', '.join(bad)+'\n')
    print('Native design tokens: '+('verified' if a.check else 'generated'))
if __name__=='__main__':main()
